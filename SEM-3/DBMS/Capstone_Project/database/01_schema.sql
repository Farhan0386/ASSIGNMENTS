-- PHASE 1 — PostgreSQL schema
-- Execute only against the dedicated, disposable payroll_db database as a PostgreSQL superuser.
-- The schema is intentionally rebuilt by this script. Do not run against a database containing other work.

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'payroll_owner') THEN
        CREATE ROLE payroll_owner NOLOGIN;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'payroll_app') THEN
        CREATE ROLE payroll_app LOGIN PASSWORD 'dev_only_change_me';
    END IF;
END $$;

-- Existing payroll_app passwords are preserved; change the local demo password manually if needed.
GRANT CONNECT ON DATABASE payroll_db TO payroll_app;
DROP SCHEMA IF EXISTS payroll CASCADE;
CREATE SCHEMA payroll AUTHORIZATION payroll_owner;
GRANT USAGE ON SCHEMA payroll TO payroll_app;

SET ROLE payroll_owner;
SET search_path TO payroll, public;

CREATE TABLE department (
    department_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_name VARCHAR(80) NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE designation (
    designation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    designation_name VARCHAR(80) NOT NULL UNIQUE
);

CREATE TABLE employee (
    employee_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_code VARCHAR(20) NOT NULL UNIQUE,
    full_name VARCHAR(120) NOT NULL,
    email VARCHAR(160) NOT NULL UNIQUE,
    phone VARCHAR(25),
    hire_date DATE NOT NULL,
    employment_status VARCHAR(12) NOT NULL DEFAULT 'ACTIVE'
        CHECK (employment_status IN ('ACTIVE', 'INACTIVE')),
    department_id BIGINT NOT NULL REFERENCES department(department_id),
    designation_id BIGINT NOT NULL REFERENCES designation(designation_id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE user_account (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(60) NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    role VARCHAR(12) NOT NULL CHECK (role IN ('HR_ADMIN', 'EMPLOYEE')),
    employee_id BIGINT UNIQUE REFERENCES employee(employee_id) ON DELETE RESTRICT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT user_role_employee_link_ck CHECK (
        (role = 'EMPLOYEE' AND employee_id IS NOT NULL) OR
        (role = 'HR_ADMIN' AND employee_id IS NULL)
    )
);

-- Enforce case-insensitive username uniqueness because authentication lookup is case-insensitive.
CREATE UNIQUE INDEX user_account_username_lower_uq ON user_account (LOWER(username));

CREATE TABLE attendance (
    attendance_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id BIGINT NOT NULL REFERENCES employee(employee_id) ON DELETE RESTRICT,
    attendance_date DATE NOT NULL,
    check_in TIME,
    check_out TIME,
    status VARCHAR(16) NOT NULL
        CHECK (status IN ('PRESENT', 'ABSENT', 'HALF_DAY', 'WORK_FROM_HOME')),
    remarks VARCHAR(250),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT attendance_employee_date_uq UNIQUE (employee_id, attendance_date),
    CONSTRAINT attendance_time_ck CHECK (
        check_out IS NULL OR (check_in IS NOT NULL AND check_out > check_in)
    ),
    CONSTRAINT attendance_absent_time_ck CHECK (
        status <> 'ABSENT' OR (check_in IS NULL AND check_out IS NULL)
    ),
    CONSTRAINT attendance_present_time_ck CHECK (
        status = 'ABSENT' OR check_in IS NOT NULL
    )
);

CREATE TABLE leave_type (
    leave_type_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    leave_type_name VARCHAR(50) NOT NULL UNIQUE,
    is_paid BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE leave_request (
    leave_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id BIGINT NOT NULL REFERENCES employee(employee_id) ON DELETE RESTRICT,
    leave_type_id BIGINT NOT NULL REFERENCES leave_type(leave_type_id),
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    reason VARCHAR(500),
    status VARCHAR(12) NOT NULL DEFAULT 'PENDING'
        CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED')),
    reviewed_by BIGINT REFERENCES user_account(user_id),
    reviewed_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT leave_dates_ck CHECK (end_date >= start_date),
    CONSTRAINT leave_review_fields_ck CHECK (
        (status = 'PENDING' AND reviewed_by IS NULL AND reviewed_at IS NULL) OR
        (status IN ('APPROVED', 'REJECTED') AND reviewed_by IS NOT NULL AND reviewed_at IS NOT NULL)
    )
);

CREATE TABLE company_holiday (
    holiday_date DATE PRIMARY KEY,
    holiday_name VARCHAR(120) NOT NULL
);

CREATE TABLE salary_structure (
    salary_structure_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id BIGINT NOT NULL REFERENCES employee(employee_id) ON DELETE RESTRICT,
    effective_from DATE NOT NULL,
    effective_to DATE,
    basic_salary NUMERIC(12,2) NOT NULL CHECK (basic_salary > 0),
    hra NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (hra >= 0),
    special_allowance NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (special_allowance >= 0),
    other_allowance NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (other_allowance >= 0),
    pf_rate_percent NUMERIC(5,2) NOT NULL DEFAULT 12.00
        CHECK (pf_rate_percent BETWEEN 0 AND 100),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT salary_effective_dates_ck CHECK (
        effective_to IS NULL OR effective_to >= effective_from
    ),
    CONSTRAINT salary_effective_from_month_ck CHECK (EXTRACT(DAY FROM effective_from) = 1),
    CONSTRAINT salary_effective_to_month_ck CHECK (
        effective_to IS NULL OR effective_to =
        (DATE_TRUNC('month', effective_to) + INTERVAL '1 month - 1 day')::DATE
    )
);

-- Lower-inclusive, upper-exclusive tax bands. The last band must have NULL upper_limit.
CREATE TABLE tax_bracket (
    tax_bracket_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tax_year INTEGER NOT NULL CHECK (tax_year BETWEEN 2000 AND 2100),
    lower_limit NUMERIC(14,2) NOT NULL CHECK (lower_limit >= 0),
    upper_limit NUMERIC(14,2),
    rate_percent NUMERIC(5,2) NOT NULL CHECK (rate_percent BETWEEN 0 AND 100),
    CONSTRAINT tax_bracket_range_ck CHECK (
        upper_limit IS NULL OR upper_limit > lower_limit
    ),
    CONSTRAINT tax_bracket_lower_uq UNIQUE (tax_year, lower_limit)
);

CREATE TABLE payroll_run (
    run_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pay_year INTEGER NOT NULL CHECK (pay_year BETWEEN 2000 AND 2100),
    pay_month INTEGER NOT NULL CHECK (pay_month BETWEEN 1 AND 12),
    status VARCHAR(12) NOT NULL DEFAULT 'DRAFT'
        CHECK (status IN ('DRAFT', 'PROCESSING', 'PROCESSED')),
    processed_by BIGINT REFERENCES user_account(user_id),
    processed_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT payroll_run_period_uq UNIQUE (pay_year, pay_month),
    CONSTRAINT payroll_run_processed_ck CHECK (
        (status <> 'PROCESSED') OR (processed_by IS NOT NULL AND processed_at IS NOT NULL)
    )
);

-- Snapshot fields intentionally preserve historical payslips after salary revisions.
CREATE TABLE payroll_entry (
    entry_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id BIGINT NOT NULL REFERENCES payroll_run(run_id) ON DELETE CASCADE,
    employee_id BIGINT NOT NULL REFERENCES employee(employee_id) ON DELETE RESTRICT,
    salary_structure_id BIGINT NOT NULL REFERENCES salary_structure(salary_structure_id),
    basic_salary NUMERIC(12,2) NOT NULL CHECK (basic_salary >= 0),
    hra NUMERIC(12,2) NOT NULL CHECK (hra >= 0),
    special_allowance NUMERIC(12,2) NOT NULL CHECK (special_allowance >= 0),
    other_allowance NUMERIC(12,2) NOT NULL CHECK (other_allowance >= 0),
    gross_salary NUMERIC(12,2) NOT NULL CHECK (gross_salary >= 0),
    working_days INTEGER NOT NULL CHECK (working_days >= 0),
    unpaid_days NUMERIC(6,2) NOT NULL CHECK (unpaid_days >= 0),
    attendance_deduction NUMERIC(12,2) NOT NULL CHECK (attendance_deduction >= 0),
    pf_deduction NUMERIC(12,2) NOT NULL CHECK (pf_deduction >= 0),
    tax_deduction NUMERIC(12,2) NOT NULL CHECK (tax_deduction >= 0),
    net_salary NUMERIC(12,2) NOT NULL CHECK (net_salary >= 0),
    generated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT payroll_entry_run_employee_uq UNIQUE (run_id, employee_id)
);

-- Row-level security: app.user_role/app.employee_id are set server-side per DB connection.
ALTER TABLE employee ENABLE ROW LEVEL SECURITY;
ALTER TABLE user_account ENABLE ROW LEVEL SECURITY;
ALTER TABLE attendance ENABLE ROW LEVEL SECURITY;
ALTER TABLE leave_request ENABLE ROW LEVEL SECURITY;
ALTER TABLE salary_structure ENABLE ROW LEVEL SECURITY;
ALTER TABLE payroll_run ENABLE ROW LEVEL SECURITY;
ALTER TABLE payroll_entry ENABLE ROW LEVEL SECURITY;

CREATE POLICY employee_read_scope ON employee FOR SELECT TO payroll_app
USING (
    current_setting('app.user_role', true) = 'HR_ADMIN'
    OR employee_id = NULLIF(current_setting('app.employee_id', true), '')::BIGINT
);
CREATE POLICY employee_hr_write ON employee FOR ALL TO payroll_app
USING (current_setting('app.user_role', true) = 'HR_ADMIN')
WITH CHECK (current_setting('app.user_role', true) = 'HR_ADMIN');

CREATE POLICY user_account_read_scope ON user_account FOR SELECT TO payroll_app
USING (
    current_setting('app.user_role', true) = 'HR_ADMIN'
    OR user_id = NULLIF(current_setting('app.user_id', true), '')::BIGINT
);
CREATE POLICY user_account_hr_insert ON user_account FOR INSERT TO payroll_app
WITH CHECK (current_setting('app.user_role', true) = 'HR_ADMIN');
CREATE POLICY user_account_hr_update ON user_account FOR UPDATE TO payroll_app
USING (current_setting('app.user_role', true) = 'HR_ADMIN')
WITH CHECK (current_setting('app.user_role', true) = 'HR_ADMIN');

CREATE POLICY attendance_read_scope ON attendance FOR SELECT TO payroll_app
USING (
    current_setting('app.user_role', true) = 'HR_ADMIN'
    OR employee_id = NULLIF(current_setting('app.employee_id', true), '')::BIGINT
);
CREATE POLICY attendance_hr_insert ON attendance FOR INSERT TO payroll_app
WITH CHECK (current_setting('app.user_role', true) = 'HR_ADMIN');
CREATE POLICY attendance_hr_update ON attendance FOR UPDATE TO payroll_app
USING (current_setting('app.user_role', true) = 'HR_ADMIN')
WITH CHECK (current_setting('app.user_role', true) = 'HR_ADMIN');
CREATE POLICY attendance_hr_delete ON attendance FOR DELETE TO payroll_app
USING (current_setting('app.user_role', true) = 'HR_ADMIN');

CREATE POLICY leave_read_scope ON leave_request FOR SELECT TO payroll_app
USING (
    current_setting('app.user_role', true) = 'HR_ADMIN'
    OR employee_id = NULLIF(current_setting('app.employee_id', true), '')::BIGINT
);
CREATE POLICY leave_hr_insert ON leave_request FOR INSERT TO payroll_app
WITH CHECK (
    current_setting('app.user_role', true) = 'HR_ADMIN'
    AND status = 'PENDING'
    AND reviewed_by IS NULL
    AND reviewed_at IS NULL
);
CREATE POLICY leave_hr_update ON leave_request FOR UPDATE TO payroll_app
USING (current_setting('app.user_role', true) = 'HR_ADMIN')
WITH CHECK (current_setting('app.user_role', true) = 'HR_ADMIN');

CREATE POLICY salary_read_scope ON salary_structure FOR SELECT TO payroll_app
USING (
    current_setting('app.user_role', true) = 'HR_ADMIN'
    OR employee_id = NULLIF(current_setting('app.employee_id', true), '')::BIGINT
);
CREATE POLICY salary_hr_insert ON salary_structure FOR INSERT TO payroll_app
WITH CHECK (current_setting('app.user_role', true) = 'HR_ADMIN');
CREATE POLICY salary_hr_update ON salary_structure FOR UPDATE TO payroll_app
USING (current_setting('app.user_role', true) = 'HR_ADMIN')
WITH CHECK (current_setting('app.user_role', true) = 'HR_ADMIN');
CREATE POLICY salary_hr_delete ON salary_structure FOR DELETE TO payroll_app
USING (current_setting('app.user_role', true) = 'HR_ADMIN');

CREATE POLICY payroll_run_read_scope ON payroll_run FOR SELECT TO payroll_app
USING (
    current_setting('app.user_role', true) = 'HR_ADMIN'
    OR EXISTS (
        SELECT 1 FROM payroll_entry pe
        WHERE pe.run_id = payroll_run.run_id
          AND pe.employee_id = NULLIF(current_setting('app.employee_id', true), '')::BIGINT
    )
);
CREATE POLICY payroll_entry_read_scope ON payroll_entry FOR SELECT TO payroll_app
USING (
    current_setting('app.user_role', true) = 'HR_ADMIN'
    OR employee_id = NULLIF(current_setting('app.employee_id', true), '')::BIGINT
);

RESET ROLE;

GRANT SELECT ON payroll.department, payroll.designation, payroll.leave_type,
    payroll.company_holiday, payroll.tax_bracket TO payroll_app;
GRANT SELECT, INSERT, UPDATE, DELETE ON payroll.employee,
    payroll.attendance, payroll.leave_request, payroll.salary_structure TO payroll_app;
GRANT SELECT ON payroll.payroll_run, payroll.payroll_entry TO payroll_app;
GRANT SELECT (user_id, username, role, employee_id, is_active, created_at)
    ON payroll.user_account TO payroll_app;
GRANT INSERT (username, password_hash, role, employee_id, is_active)
    ON payroll.user_account TO payroll_app;
GRANT UPDATE (is_active) ON payroll.user_account TO payroll_app;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA payroll TO payroll_app;
